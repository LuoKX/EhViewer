use std::io::{self, Read, Seek};

use thiserror::Error;
use zip::result::ZipError;
use zip::{CompressionMethod, ZipArchive};

/// The metadata entry appended to every CBZ generated by the application.
pub const COMIC_INFO_ENTRY_NAME: &str = "ComicInfo.xml";

/// The largest one-based page number representable by the writer's name contract.
pub const MAX_GENERATED_CBZ_IMAGES: usize = 99_999_999;

const MAX_IMAGE_EXTENSION_LENGTH: usize = 16;

/// A successful structural and CRC validation summary.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct CbzValidation {
    /// Number of sequential image entries that were validated.
    pub image_count: usize,
    /// Total number of entries, including [`COMIC_INFO_ENTRY_NAME`].
    pub entry_count: usize,
    /// Sum of every entry's uncompressed byte length.
    pub uncompressed_bytes: u64,
}

/// A deterministic failure produced while validating an application-generated CBZ.
#[derive(Debug, Error)]
pub enum CbzValidationError {
    /// The caller supplied zero images or exceeded the eight-digit page namespace.
    #[error("expected image count must be between 1 and {MAX_GENERATED_CBZ_IMAGES}")]
    InvalidExpectedImageCount,
    /// The input is not a readable ZIP archive.
    #[error("CBZ central directory is invalid")]
    OpenArchive(#[source] ZipError),
    /// The archive does not contain exactly the expected pages plus metadata.
    #[error("CBZ entry count mismatch: expected {expected}, found {actual}")]
    EntryCount {
        /// Expected page entries plus one metadata entry.
        expected: usize,
        /// Number of entries declared by the archive.
        actual: usize,
    },
    /// One central-directory entry could not be opened safely.
    #[error("CBZ entry {index} is invalid")]
    OpenEntry {
        /// Zero-based archive entry position.
        index: usize,
        /// ZIP parser failure.
        #[source]
        source: ZipError,
    },
    /// Application-generated archives contain regular files only.
    #[error("CBZ entry {index} is not a regular file")]
    NonRegularEntry {
        /// Zero-based archive entry position.
        index: usize,
    },
    /// Application-generated archives are never encrypted.
    #[error("CBZ entry {index} is encrypted")]
    EncryptedEntry {
        /// Zero-based archive entry position.
        index: usize,
    },
    /// The existing native writer emits Stored entries only.
    #[error("CBZ entry {index} is not stored without compression")]
    UnsupportedCompression {
        /// Zero-based archive entry position.
        index: usize,
    },
    /// Page names must be sequential and metadata must be the final entry.
    #[error("CBZ entry {index} has an unexpected name")]
    UnexpectedEntryName {
        /// Zero-based archive entry position.
        index: usize,
    },
    /// A page or metadata entry contains no bytes.
    #[error("CBZ entry {index} is empty")]
    EmptyEntry {
        /// Zero-based archive entry position.
        index: usize,
    },
    /// Reading an entry to EOF failed, including CRC mismatches.
    #[error("CBZ entry {index} failed integrity validation")]
    ReadEntry {
        /// Zero-based archive entry position.
        index: usize,
        /// Underlying read or CRC failure.
        #[source]
        source: io::Error,
    },
    /// Declared uncompressed lengths overflow the summary representation.
    #[error("CBZ uncompressed size overflow")]
    UncompressedSizeOverflow,
}

/// Validates a CBZ written by the application's native archive writer.
///
/// The contract requires exactly `expected_images` sequential page entries
/// named `00000001.<extension>` through the expected final index, followed by
/// exactly one [`COMIC_INFO_ENTRY_NAME`]. Every entry must be a non-empty,
/// unencrypted, regular Stored file. Reading each entry fully forces the ZIP
/// reader to verify its CRC without allocating the entry contents.
///
/// Because compressed entries are rejected before their payload is read, this
/// validator cannot amplify a small archive through decompression.
///
/// # Errors
///
/// Returns [`CbzValidationError`] for invalid caller expectations, malformed ZIP
/// metadata, contract mismatches, unsupported entry properties, read failures,
/// CRC mismatches, or size overflow.
pub fn validate_generated_cbz<R>(
    reader: R,
    expected_images: usize,
) -> Result<CbzValidation, CbzValidationError>
where
    R: Read + Seek,
{
    if expected_images == 0 || expected_images > MAX_GENERATED_CBZ_IMAGES {
        return Err(CbzValidationError::InvalidExpectedImageCount);
    }

    let expected_entries = expected_images
        .checked_add(1)
        .ok_or(CbzValidationError::InvalidExpectedImageCount)?;
    let mut archive = ZipArchive::new(reader).map_err(CbzValidationError::OpenArchive)?;
    if archive.len() != expected_entries {
        return Err(CbzValidationError::EntryCount {
            expected: expected_entries,
            actual: archive.len(),
        });
    }

    let mut uncompressed_bytes = 0_u64;
    for index in 0..expected_entries {
        let declared_size = {
            let entry = match archive.by_index_raw(index) {
                Ok(entry) => entry,
                Err(source) => return Err(CbzValidationError::OpenEntry { index, source }),
            };
            validate_entry_metadata(&entry, index, expected_images)?;
            entry.size()
        };

        let mut entry = match archive.by_index(index) {
            Ok(entry) => entry,
            Err(source) => return Err(CbzValidationError::OpenEntry { index, source }),
        };
        io::copy(&mut entry, &mut io::sink())
            .map_err(|source| CbzValidationError::ReadEntry { index, source })?;
        uncompressed_bytes = uncompressed_bytes
            .checked_add(declared_size)
            .ok_or(CbzValidationError::UncompressedSizeOverflow)?;
    }

    Ok(CbzValidation {
        image_count: expected_images,
        entry_count: expected_entries,
        uncompressed_bytes,
    })
}

fn validate_entry_metadata<R>(
    entry: &zip::read::ZipFile<'_, R>,
    index: usize,
    expected_images: usize,
) -> Result<(), CbzValidationError>
where
    R: Read + ?Sized,
{
    if !entry.is_file() {
        return Err(CbzValidationError::NonRegularEntry { index });
    }
    if entry.encrypted() {
        return Err(CbzValidationError::EncryptedEntry { index });
    }
    if entry.compression() != CompressionMethod::Stored {
        return Err(CbzValidationError::UnsupportedCompression { index });
    }

    let has_expected_name = if index < expected_images {
        is_generated_page_name(entry.name(), index + 1)
    } else {
        entry.name() == COMIC_INFO_ENTRY_NAME
    };
    if !has_expected_name {
        return Err(CbzValidationError::UnexpectedEntryName { index });
    }
    if entry.size() == 0 {
        return Err(CbzValidationError::EmptyEntry { index });
    }
    Ok(())
}

fn is_generated_page_name(name: &str, one_based_index: usize) -> bool {
    let prefix = format!("{one_based_index:08}.");
    name.strip_prefix(&prefix).is_some_and(|extension| {
        (1..=MAX_IMAGE_EXTENSION_LENGTH).contains(&extension.len())
            && extension
                .bytes()
                .all(|byte| byte.is_ascii_lowercase() || byte.is_ascii_digit())
    })
}

#[cfg(test)]
mod tests {
    use std::io::{Cursor, Write};

    use zip::write::SimpleFileOptions;
    use zip::{CompressionMethod, ZipWriter};

    use super::{
        CbzValidation, CbzValidationError, MAX_GENERATED_CBZ_IMAGES, is_generated_page_name,
        validate_generated_cbz,
    };

    const PAGE_ONE: &[u8] = b"page-one-unique-payload";
    const PAGE_TWO: &[u8] = b"page-two-unique-payload";
    const COMIC_INFO: &[u8] = b"<ComicInfo><PageCount>2</PageCount></ComicInfo>";

    #[derive(Clone, Copy)]
    struct TestEntry<'a> {
        name: &'a str,
        contents: &'a [u8],
        compression: CompressionMethod,
    }

    fn stored_entry<'a>(name: &'a str, contents: &'a [u8]) -> TestEntry<'a> {
        TestEntry {
            name,
            contents,
            compression: CompressionMethod::Stored,
        }
    }

    fn zip_bytes(entries: &[TestEntry<'_>]) -> Vec<u8> {
        let cursor = Cursor::new(Vec::new());
        let mut writer = ZipWriter::new(cursor);
        for entry in entries {
            let options = SimpleFileOptions::default()
                .compression_method(entry.compression)
                .unix_permissions(0o644);
            writer
                .start_file(entry.name, options)
                .expect("test entry should start");
            writer
                .write_all(entry.contents)
                .expect("test entry should write");
        }
        writer
            .finish()
            .expect("test archive should finish")
            .into_inner()
    }

    fn valid_archive() -> Vec<u8> {
        zip_bytes(&[
            stored_entry("00000001.jpg", PAGE_ONE),
            stored_entry("00000002.webp", PAGE_TWO),
            stored_entry("ComicInfo.xml", COMIC_INFO),
        ])
    }

    #[test]
    fn validates_exact_generated_cbz_shape_and_all_bytes() {
        let validation = validate_generated_cbz(Cursor::new(valid_archive()), 2)
            .expect("generated archive should validate");
        assert_eq!(
            validation,
            CbzValidation {
                image_count: 2,
                entry_count: 3,
                uncompressed_bytes: u64::try_from(
                    PAGE_ONE.len() + PAGE_TWO.len() + COMIC_INFO.len()
                )
                .expect("fixture size fits u64"),
            }
        );
        assert!(is_generated_page_name("99999999.avif", 99_999_999));
    }

    #[test]
    fn rejects_invalid_expected_image_counts_before_zip_parsing() {
        assert!(matches!(
            validate_generated_cbz(Cursor::new(Vec::new()), 0),
            Err(CbzValidationError::InvalidExpectedImageCount)
        ));
        assert!(matches!(
            validate_generated_cbz(Cursor::new(Vec::new()), MAX_GENERATED_CBZ_IMAGES + 1),
            Err(CbzValidationError::InvalidExpectedImageCount)
        ));
    }

    #[test]
    fn rejects_malformed_archives_and_wrong_entry_counts() {
        assert!(matches!(
            validate_generated_cbz(Cursor::new(b"not-a-zip".to_vec()), 1),
            Err(CbzValidationError::OpenArchive(_))
        ));
        assert!(matches!(
            validate_generated_cbz(Cursor::new(valid_archive()), 1),
            Err(CbzValidationError::EntryCount {
                expected: 2,
                actual: 3
            })
        ));
    }

    #[test]
    fn rejects_non_regular_and_empty_entries() {
        let cursor = Cursor::new(Vec::new());
        let mut writer = ZipWriter::new(cursor);
        writer
            .add_directory("unexpected/", SimpleFileOptions::default())
            .expect("directory should write");
        writer
            .start_file("ComicInfo.xml", SimpleFileOptions::default())
            .expect("metadata should start");
        writer.write_all(COMIC_INFO).expect("metadata should write");
        let directory_archive = writer.finish().expect("archive should finish").into_inner();
        assert!(matches!(
            validate_generated_cbz(Cursor::new(directory_archive), 1),
            Err(CbzValidationError::NonRegularEntry { index: 0 })
        ));

        let empty_page = zip_bytes(&[
            stored_entry("00000001.jpg", b""),
            stored_entry("ComicInfo.xml", COMIC_INFO),
        ]);
        assert!(matches!(
            validate_generated_cbz(Cursor::new(empty_page), 1),
            Err(CbzValidationError::EmptyEntry { index: 0 })
        ));
    }

    #[test]
    fn rejects_non_sequential_unsafe_or_missing_metadata_names() {
        for invalid_page_name in [
            "00000002.jpg",
            "../00000001.jpg",
            "00000001.JPG",
            "00000001.",
            "00000001.extension-is-too-long",
        ] {
            let bytes = zip_bytes(&[
                stored_entry(invalid_page_name, PAGE_ONE),
                stored_entry("ComicInfo.xml", COMIC_INFO),
            ]);
            assert!(matches!(
                validate_generated_cbz(Cursor::new(bytes), 1),
                Err(CbzValidationError::UnexpectedEntryName { index: 0 })
            ));
        }

        let missing_metadata = zip_bytes(&[
            stored_entry("00000001.jpg", PAGE_ONE),
            stored_entry("metadata.xml", COMIC_INFO),
        ]);
        assert!(matches!(
            validate_generated_cbz(Cursor::new(missing_metadata), 1),
            Err(CbzValidationError::UnexpectedEntryName { index: 1 })
        ));
    }

    #[test]
    fn rejects_compressed_entries_before_decompression() {
        let bytes = zip_bytes(&[
            TestEntry {
                name: "00000001.jpg",
                contents: PAGE_ONE,
                compression: CompressionMethod::Deflated,
            },
            stored_entry("ComicInfo.xml", COMIC_INFO),
        ]);
        assert!(matches!(
            validate_generated_cbz(Cursor::new(bytes), 1),
            Err(CbzValidationError::UnsupportedCompression { index: 0 })
        ));
    }

    #[test]
    fn rejects_encrypted_entry_flags_without_reading_payloads() {
        let mut bytes = zip_bytes(&[
            stored_entry("00000001.jpg", PAGE_ONE),
            stored_entry("ComicInfo.xml", COMIC_INFO),
        ]);
        set_first_entry_encrypted(&mut bytes);
        assert!(matches!(
            validate_generated_cbz(Cursor::new(bytes), 1),
            Err(CbzValidationError::EncryptedEntry { index: 0 })
        ));
    }

    #[test]
    fn reads_entries_to_eof_and_rejects_crc_corruption() {
        let mut bytes = valid_archive();
        let payload_offset = bytes
            .windows(PAGE_ONE.len())
            .position(|window| window == PAGE_ONE)
            .expect("stored payload should be present");
        bytes[payload_offset] ^= 0x01;
        assert!(matches!(
            validate_generated_cbz(Cursor::new(bytes), 2),
            Err(CbzValidationError::ReadEntry { index: 0, .. })
        ));
    }

    fn set_first_entry_encrypted(bytes: &mut [u8]) {
        const LOCAL_HEADER: [u8; 4] = [0x50, 0x4b, 0x03, 0x04];
        const CENTRAL_HEADER: [u8; 4] = [0x50, 0x4b, 0x01, 0x02];
        let local = bytes
            .windows(LOCAL_HEADER.len())
            .position(|window| window == LOCAL_HEADER)
            .expect("local header should exist");
        let central = bytes
            .windows(CENTRAL_HEADER.len())
            .position(|window| window == CENTRAL_HEADER)
            .expect("central header should exist");
        bytes[local + 6] |= 0x01;
        bytes[central + 8] |= 0x01;
    }
}
