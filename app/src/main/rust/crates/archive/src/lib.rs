//! Safe, host-testable CBZ writing, validation, and bounded ZIP/CBZ reading.
//!
//! This crate deliberately owns no Android, JNI, path, database, or download
//! lifecycle behavior. [`writer`] emits the exact generated Stored-ZIP shape,
//! this module validates it, and [`reader`] indexes and extracts the supported
//! unencrypted Stored/Deflate ZIP subset behind bounded, host-testable APIs.
//!
//! # Example
//!
//! ```no_run
//! use std::fs::File;
//!
//! use eh_archive::reader::ZipArchiveReader;
//!
//! let source = File::open("gallery.cbz")?;
//! let reader = ZipArchiveReader::open(source, true)?;
//! assert!(reader.entry_count() > 0);
//! # Ok::<(), Box<dyn std::error::Error>>(())
//! ```

