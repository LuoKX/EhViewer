#!/usr/bin/env python3
"""Generate Rust geometry from the reviewed original Android vector, never redraw it.

Only the canonical sign-in logo subset is supported. Source changes require
explicit review; --check compares bytes and never rewrites generated source.
"""

import argparse
import hashlib
import math
import re
import subprocess
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "app/src/main/res/drawable/ic_launcher_foreground.xml"
OUTPUT = ROOT / "native/src/signin_artwork_data.rs"
EXPECTED_SHA = "7b5508de9a8564a86cd7461bfcf0d88b52a492653011f4b7e0bf20cc48570c89"
ANDROID = "{http://schemas.android.com/apk/res/android}"
TOKEN = re.compile(r"[MHVLCZ]|[-+]?(?:\d*\.)?\d+(?:[eE][-+]?\d+)?")


def number(value: str) -> float:
    """Require bounded finite source geometry."""
    try:
        result = float(value)
    except ValueError as error:
        raise ValueError("Invalid vector number") from error
    if not math.isfinite(result) or abs(result) > 4096:
        raise ValueError("Vector number outside supported geometry budget")
    return result


def literal(value: float) -> str:
    """Emit an unambiguous Rust f32 literal."""
    result = str(value)
    return result if "." in result or "e" in result else result + ".0"


def point(values: list[float]) -> str:
    return "[" + ", ".join(literal(value) for value in values) + "]"


def path_commands(value: str) -> list[tuple[str, list[float]]]:
    """Parse reviewed absolute M/H/V/L/C/Z only; reject everything else."""
    tokens = TOKEN.findall(value)
    if re.sub(r"[\s,]+", "", TOKEN.sub("", value)):
        raise ValueError("Unsupported vector path command")
    commands = []
    index = 0
    position = [0.0, 0.0]
    widths = {"M": 2, "H": 1, "V": 1, "L": 2, "C": 6, "Z": 0}
    while index < len(tokens):
        command = tokens[index]
        if command not in widths:
            raise ValueError("Implicit or unsupported vector path command")
        width = widths[command]
        if index + width >= len(tokens) and width:
            raise ValueError("Incomplete vector path command")
        values = [number(token) for token in tokens[index + 1 : index + 1 + width]]
        index += width + 1
        if command == "H":
            position = [values[0], position[1]]
            commands.append(("L", position))
        elif command == "V":
            position = [position[0], values[0]]
            commands.append(("L", position))
        else:
            if command in {"M", "L", "C"}:
                position = values[-2:]
            commands.append((command, values))
    if not commands or commands[0][0] != "M":
        raise ValueError("Vector path must start with Move")
    return commands


def color(value: str) -> str:
    if not re.fullmatch(r"#[0-9a-fA-F]{6}", value):
        raise ValueError("Only canonical opaque RGB colors supported")
    return (
        "["
        + ", ".join(str(int(value[index : index + 2], 16)) for index in (1, 3, 5))
        + "]"
    )


def generate(payload: bytes) -> str:
    """Derive coordinates, transforms, colors and draw order from reviewed bytes."""
    if hashlib.sha256(payload).hexdigest() != EXPECTED_SHA:
        raise ValueError(
            "Canonical logo source drift; review before changing EXPECTED_SHA"
        )
    # Hash-allowlisted repository XML only, not untrusted runtime/user input.
    root = ET.fromstring(payload)  # noqa: S314
    [group] = list(root)
    if root.tag != "vector" or group.tag != "group":
        raise ValueError("Unsupported vector tree")
    viewport = [
        number(root.attrib[ANDROID + key])
        for key in ("viewportWidth", "viewportHeight")
    ]
    scale = [number(group.attrib[ANDROID + key]) for key in ("scaleX", "scaleY")]
    translate = [
        number(group.attrib[ANDROID + key]) for key in ("translateX", "translateY")
    ]
    if scale[0] != scale[1] or scale[0] <= 0 or min(viewport) <= 0:
        raise ValueError("Only positive uniform logo transforms supported")
    lines = [
        "// Generated by scripts/export_signin_artwork.py; do not edit by hand.",
        "// Original asset: Copyright 2022 Tarsin Norbin; GPL-3.0-or-later.",
        f'pub(super) const SOURCE_SHA256: &str = "{EXPECTED_SHA}";',
        f"pub(super) const VIEWPORT: [f32; 2] = {point(viewport)};",
        f"pub(super) const GROUP_SCALE: f32 = {literal(scale[0])};",
        f"pub(super) const GROUP_TRANSLATE: [f32; 2] = {point(translate)};",
        "pub(super) const STROKES: &[super::SourceStroke] = &[",
    ]
    paths = list(group)
    for path in paths[:-1]:
        attrs = path.attrib
        commands = path_commands(attrs[ANDROID + "pathData"])
        if (
            path.tag != "path"
            or len(commands) != 2
            or [kind for kind, _ in commands] != ["M", "L"]
        ):
            raise ValueError("Only individual canonical stroke segments supported")
        if (
            attrs[ANDROID + "strokeLineCap"] != "round"
            or attrs[ANDROID + "fillColor"] != "#00000000"
        ):
            raise ValueError("Unsupported logo stroke style")
        width = number(attrs[ANDROID + "strokeWidth"])
        if width <= 0:
            raise ValueError("Invalid logo stroke width")
        lines.append(
            "    super::SourceStroke { "
            + f"from: {point(commands[0][1])}, to: {point(commands[1][1])}, "
            + f"width: {literal(width)}, color: {color(attrs[ANDROID + 'strokeColor'])}"
            + " },"
        )
    lines.append("];")
    fill = paths[-1].attrib
    if fill[ANDROID + "fillType"] != "evenOdd":
        raise ValueError("Unsupported logo fill rule")
    commands = path_commands(fill[ANDROID + "pathData"])
    if commands[-1][0] != "Z":
        raise ValueError("Canonical fill must close")
    lines.append(
        f"pub(super) const FILL_COLOR: [u8; 3] = {color(fill[ANDROID + 'fillColor'])};"
    )
    lines.append("pub(super) const FILL: &[super::SourceCommand] = &[")
    for kind, values in commands:
        if kind in {"M", "L"}:
            variant = "Move" if kind == "M" else "Line"
            lines.append(f"    super::SourceCommand::{variant}({point(values)}),")
        elif kind == "C":
            lines.append(
                f"    super::SourceCommand::Cubic([{point(values[:2])}, {point(values[2:4])}, {point(values[4:])}]),"
            )
        elif kind == "Z":
            lines.append("    super::SourceCommand::Close,")
        else:
            raise ValueError("Unsupported fill path")
    lines.append("];")
    return subprocess.check_output(
        ["rustfmt", "--edition=2024", "--emit=stdout"],
        input="\n".join(lines) + "\n",
        text=True,
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=SOURCE)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        content = generate(args.source.read_bytes()).encode("utf-8")
        if args.check:
            if not args.output.is_file() or args.output.read_bytes() != content:
                raise ValueError("Generated artwork geometry drift")
        else:
            args.output.write_bytes(content)
    except (
        OSError,
        ValueError,
        KeyError,
        ET.ParseError,
        subprocess.CalledProcessError,
    ) as error:
        parser.exit(1, f"SignIn artwork generation failed: {error}\n")
    print(
        "Verified original artwork geometry"
        if args.check
        else "Generated original artwork geometry"
    )


if __name__ == "__main__":
    main()
